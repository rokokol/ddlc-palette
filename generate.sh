  } >"$out/vim-ddlc-$V.vim"

done

# Swatch card for the README — SVG so the labels use the reader's own font
{
  cols=4
  sw=170
  sh=88
  n=$(flat | wc -l)
  rows=$(((n + cols - 1) / cols))
  echo "<!-- $banner -->"
  echo "<svg xmlns=\"http://www.w3.org/2000/svg\" width=\"$((cols * sw))\" height=\"$((rows * sh))\" viewBox=\"0 0 $((cols * sw)) $((rows * sh))\" font-family=\"ui-monospace, monospace\">"
  i=0
  while read -r _ name hex; do
    x=$(((i % cols) * sw))
    y=$(((i / cols) * sh))
    # Dark swatches need light text; luminance from the top two bits is enough here
    r=$((16#${hex:1:2}))
    g=$((16#${hex:3:2}))
    b=$((16#${hex:5:2}))
    lum=$(((r * 299 + g * 587 + b * 114) / 1000))
    fg="#111111"
    [[ $lum -lt 140 ]] && fg="#FFFFFF"
    echo "  <rect x=\"$x\" y=\"$y\" width=\"$sw\" height=\"$sh\" fill=\"$hex\"/>"
    echo "  <text x=\"$((x + 14))\" y=\"$((y + 36))\" fill=\"$fg\" font-size=\"17\">$name</text>"
    echo "  <text x=\"$((x + 14))\" y=\"$((y + 62))\" fill=\"$fg\" font-size=\"14\" opacity=\"0.75\">$hex</text>"
    i=$((i + 1))
  done < <(flat)
  echo "</svg>"
} >"$out/palette.svg"

echo "wrote $out/palette.{css,nix,sh,env,svg} and, per variant, $out/{base16-ddlc-VARIANT.yaml,kitty-ddlc-VARIANT.conf,btop-ddlc-VARIANT.theme,vim-ddlc-VARIANT.vim}"
