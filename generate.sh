    echo
    echo "\" Neovim only — plain vim has no diagnostics and simply ignores these"
    while read -r group fg bg gui; do
      [ "$fg" = "-" ] && fg=NONE || fg="$(s "$fg")"
      [ "$bg" = "-" ] && bg=NONE || bg="$(s "$bg")"
      echo "hi $group guifg=$fg guibg=$bg gui=${gui:-NONE}"
    done <<'DIAGNOSTICS'
